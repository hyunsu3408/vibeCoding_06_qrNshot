/**
 * QR Code Generator Web Application
 * Handles QR generation, layout transitions, and JPG export.
 */

document.addEventListener('DOMContentLoaded', () => {
  // DOM Elements
  const body = document.body;
  const urlForm = document.getElementById('urlForm');
  const urlInput = document.getElementById('urlInput');
  const btnSubmit = document.getElementById('btnSubmit');
  const btnClearInput = document.getElementById('btnClearInput');
  const inputCard = document.getElementById('inputCard');
  const inputMessage = document.getElementById('inputMessage');
  
  const qrDisplaySection = document.getElementById('qrDisplaySection');
  const qrCard = document.getElementById('qrCard');
  const qrcodeContainer = document.getElementById('qrcode');
  const targetUrlText = document.getElementById('targetUrlText');
  const btnDownload = document.getElementById('btnDownload');
  
  const logoBtn = document.getElementById('logoBtn');
  const btnReset = document.getElementById('btnReset');
  
  const toastPill = document.getElementById('toastPill');
  const toastText = document.getElementById('toastText');

  let currentQRCode = null;
  let currentEncodedUrl = '';
  let toastTimer = null;

  // 1. Input dynamic controls (Clear button & validation reset)
  urlInput.addEventListener('input', () => {
    if (urlInput.value.length > 0) {
      btnClearInput.style.display = 'flex';
    } else {
      btnClearInput.style.display = 'none';
    }
    clearMessage();
  });

  btnClearInput.addEventListener('click', () => {
    urlInput.value = '';
    btnClearInput.style.display = 'none';
    urlInput.focus();
    clearMessage();
  });

  // 2. Submit & QR Code Generation (Requirement 2 & 3)
  urlForm.addEventListener('submit', (e) => {
    e.preventDefault();
    generateQRCode();
  });

  function generateQRCode() {
    const rawVal = urlInput.value.trim();

    if (!rawVal) {
      showError('URL 또는 링크를 입력해 주세요.');
      shakeInput();
      urlInput.focus();
      return;
    }

    // Smart URL formatting: if user inputs 'naver.com' without scheme, auto prefix https://
    let finalUrl = rawVal;
    const hasProtocol = /^[a-zA-Z]+:\/\//i.test(rawVal);
    const hasCommonPrefix = /^(mailto|tel|sms):/i.test(rawVal);

    if (!hasProtocol && !hasCommonPrefix) {
      // Check if it resembles a domain or standard web link
      if (/^[\w.-]+\.[a-zA-Z]{2,}/.test(rawVal)) {
        finalUrl = 'https://' + rawVal;
      }
    }

    currentEncodedUrl = finalUrl;

    // Clear previous QR code elements
    qrcodeContainer.innerHTML = '';

    // Generate new high-resolution QR code
    // Using 320x320 with High Error Correction Level for crisp scanning and crisp export
    try {
      currentQRCode = new QRCode(qrcodeContainer, {
        text: finalUrl,
        width: 320,
        height: 320,
        colorDark: '#0f172a',
        colorLight: '#ffffff',
        correctLevel: QRCode.CorrectLevel.H
      });
    } catch (err) {
      console.error('QR Code generation error:', err);
      showError('QR 코드를 생성하는 중 오류가 발생했습니다.');
      return;
    }

    // Update URL preview text
    targetUrlText.textContent = finalUrl;
    targetUrlText.title = finalUrl;

    // Transition state: URL bar moves to bottom, QR code appears in center
    body.classList.add('state-generated');
    btnReset.style.display = 'inline-flex';

    // Smoothly scroll or focus to ensure visibility
    window.scrollTo({ top: 0, behavior: 'smooth' });
  }

  // 3. Download QR Code as JPG (Requirement 4)
  // Clicking either the QR Card directly or the download button triggers this
  qrCard.addEventListener('click', (e) => {
    downloadAsJPG();
  });

  // Prevent event bubbling if the dedicated download button is clicked
  btnDownload.addEventListener('click', (e) => {
    e.stopPropagation();
    downloadAsJPG();
  });

  // Keyboard accessibility for QR Card
  qrCard.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault();
      downloadAsJPG();
    }
  });

  /**
   * Captures the generated QR code and exports as a high-quality JPEG (.jpg) file.
   * Ensures a pure white background so transparent pixels don't convert to black.
   */
  function downloadAsJPG() {
    if (!currentEncodedUrl) return;

    // Obtain the source canvas or image generated by qrcode.js
    const canvas = qrcodeContainer.querySelector('canvas');
    const img = qrcodeContainer.querySelector('img');

    if (!canvas && (!img || !img.src)) {
      showError('다운로드할 QR 코드를 찾을 수 없습니다.');
      return;
    }

    // Prepare a canvas for JPG export with white background and quiet zone (margin)
    const exportCanvas = document.createElement('canvas');
    const margin = 40; // Clean white margin around the QR code

    let srcWidth = 320;
    let srcHeight = 320;

    if (canvas && canvas.width > 0) {
      srcWidth = canvas.width;
      srcHeight = canvas.height;
    } else if (img && img.naturalWidth > 0) {
      srcWidth = img.naturalWidth;
      srcHeight = img.naturalHeight;
    }

    exportCanvas.width = srcWidth + (margin * 2);
    exportCanvas.height = srcHeight + (margin * 2);

    const ctx = exportCanvas.getContext('2d');

    // 1. Pure white background (Essential for JPEG to prevent black artifact)
    ctx.fillStyle = '#FFFFFF';
    ctx.fillRect(0, 0, exportCanvas.width, exportCanvas.height);

    // 2. Draw the QR code
    if (canvas && canvas.width > 0) {
      ctx.drawImage(canvas, margin, margin, srcWidth, srcHeight);
      executeDownload(exportCanvas);
    } else if (img && img.src) {
      if (img.complete) {
        ctx.drawImage(img, margin, margin, srcWidth, srcHeight);
        executeDownload(exportCanvas);
      } else {
        img.onload = () => {
          ctx.drawImage(img, margin, margin, srcWidth, srcHeight);
          executeDownload(exportCanvas);
        };
      }
    }
  }

  function executeDownload(canvas) {
    try {
      // Export as pure image/jpeg with high quality
      const dataUrl = canvas.toDataURL('image/jpeg', 0.95);

      // Create download filename based on host/timestamp
      let hostPart = 'qrcode';
      try {
        const parsed = new URL(currentEncodedUrl);
        hostPart = parsed.hostname.replace(/[^a-zA-Z0-9.-]/g, '_');
      } catch (_) {
        hostPart = 'qrcode';
      }

      const timestamp = new Date().toISOString().slice(0, 10).replace(/-/g, '');
      const filename = `${hostPart}_${timestamp}.jpg`;

      // Trigger automatic file download
      const link = document.createElement('a');
      link.download = filename;
      link.href = dataUrl;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);

      // Show success feedback
      showToast('JPG 파일이 성공적으로 다운로드되었습니다!');
    } catch (e) {
      console.error('Download failed:', e);
      showError('JPG 저장 중 문제가 발생했습니다.');
    }
  }

  // 4. Reset & Logo Click
  function resetToInitial() {
    body.classList.remove('state-generated');
    btnReset.style.display = 'none';
    urlInput.value = '';
    btnClearInput.style.display = 'none';
    qrcodeContainer.innerHTML = '';
    currentQRCode = null;
    currentEncodedUrl = '';
    clearMessage();
    setTimeout(() => {
      urlInput.focus();
    }, 300);
  }

  logoBtn.addEventListener('click', resetToInitial);
  logoBtn.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault();
      resetToInitial();
    }
  });

  btnReset.addEventListener('click', resetToInitial);

  // 5. Utility Functions
  function showError(msg) {
    inputMessage.textContent = msg;
    inputMessage.classList.add('visible');
  }

  function clearMessage() {
    inputMessage.textContent = '';
    inputMessage.classList.remove('visible');
  }

  function shakeInput() {
    inputCard.classList.remove('shake');
    // Trigger reflow to restart animation
    void inputCard.offsetWidth;
    inputCard.classList.add('shake');
  }

  function showToast(msg) {
    if (toastTimer) clearTimeout(toastTimer);
    toastText.textContent = msg;
    toastPill.classList.add('show');

    toastTimer = setTimeout(() => {
      toastPill.classList.remove('show');
    }, 2800);
  }

  // ========================================================
  // 6. Interactive Gradient Tracking Mouse Movement
  // Dynamically morphs background gradient colors and positions
  // ========================================================
  const root = document.documentElement;
  let targetX = window.innerWidth * 0.5;
  let targetY = window.innerHeight * 0.4;
  let currentX = targetX;
  let currentY = targetY;

  function onPointerMove(x, y) {
    targetX = x;
    targetY = y;
  }

  window.addEventListener('mousemove', (e) => {
    onPointerMove(e.clientX, e.clientY);
  }, { passive: true });

  window.addEventListener('touchmove', (e) => {
    if (e.touches && e.touches.length > 0) {
      onPointerMove(e.touches[0].clientX, e.touches[0].clientY);
    }
  }, { passive: true });

  // Smooth physics-based render loop using linear interpolation (lerp)
  function updateGradientFrame() {
    // Lerp factor for smooth organic inertia
    currentX += (targetX - currentX) * 0.08;
    currentY += (targetY - currentY) * 0.08;

    const width = window.innerWidth || 1920;
    const height = window.innerHeight || 1080;

    // Normalized values: -1.0 to 1.0 (from center of screen)
    const normX = ((currentX / width) - 0.5) * 2;
    const normY = ((currentY / height) - 0.5) * 2;

    // Percentages for radial gradient positions
    const percentX = (currentX / width * 100).toFixed(2);
    const percentY = (currentY / height * 100).toFixed(2);

    // Subtle hue & brightness shifts matching the logo's amber/gold hues (#FFC000)
    // Horizontal move: subtle shift between warm peach/coral (32deg) and golden sunshine (56deg)
    // Vertical move: subtle shift in warmth and ambient brightness
    const hue1 = 44 + (normX * 12) + (normY * 5); // 32 ~ 56
    const hue2 = 28 + (normY * 12) - (normX * 8); // 16 ~ 44
    const hue3 = 50 - (normX * 10);              // 40 ~ 60

    const color1 = `hsla(${hue1.toFixed(1)}, 95%, 68%, 0.65)`;
    const color2 = `hsla(${hue2.toFixed(1)}, 92%, 76%, 0.48)`;
    const color3 = `hsla(${hue3.toFixed(1)}, 96%, 82%, 0.68)`;
    const cursorGlowColor = `hsla(${(hue1 + 4).toFixed(1)}, 98%, 62%, 0.38)`;

    root.style.setProperty('--mouse-x', `${percentX}%`);
    root.style.setProperty('--mouse-y', `${percentY}%`);
    root.style.setProperty('--cursor-x', `${currentX.toFixed(1)}px`);
    root.style.setProperty('--cursor-y', `${currentY.toFixed(1)}px`);
    root.style.setProperty('--grad-c1', color1);
    root.style.setProperty('--grad-c2', color2);
    root.style.setProperty('--grad-c3', color3);
    root.style.setProperty('--cursor-color', cursorGlowColor);

    requestAnimationFrame(updateGradientFrame);
  }

  // Start the animation loop
  requestAnimationFrame(updateGradientFrame);

  // Check URL query parameters (e.g. ?url=https://...)
  try {
    const urlParams = new URLSearchParams(window.location.search);
    const initialUrl = urlParams.get('url');
    if (initialUrl) {
      urlInput.value = initialUrl;
      btnClearInput.style.display = 'flex';
      setTimeout(() => {
        generateQRCode();
      }, 150);
    }
  } catch (e) {
    console.error('URL parameter parse error', e);
  }
});


